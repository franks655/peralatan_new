-- Create function to update updated_at column
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
   NEW.updated_at = NOW();
   RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Create triggers for updated_at
CREATE TRIGGER update_kegiatan_mekanik_updated_at
BEFORE UPDATE ON public.kegiatan_mekanik
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

CREATE TRIGGER update_rpa_updated_at
BEFORE UPDATE ON public.rpa
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

CREATE TRIGGER update_rpa_details_updated_at
BEFORE UPDATE ON public.rpa_details
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();
